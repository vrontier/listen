    <section class="prose">
      <p>
        Listening Observatory connects to live audio streams, analyses their acoustic
        structure in real time, and translates what it hears into evolving visual forms
        and textual observations. Rather than treating sound as something to be displayed
        moment by moment, the system listens across different timescales — from immediate
        frequency changes to recurring resonances, motifs, and longer-term patterns.
      </p>
    </section>

    <section class="layers" aria-label="How it listens">
      <article>
        <h2>Observation</h2>
        <p>
          Signal processing extracts frequencies, harmonics, spectral energy, entropy,
          transients, and other measurable characteristics continuously.
        </p>
      </article>
      <article>
        <h2>Memory</h2>
        <p>
          A memory layer compares current activity with what has been heard before, so
          recurring structures return with a persistent visual identity.
        </p>
      </article>
      <article>
        <h2>Visualization</h2>
        <p>
          Generated live in the browser. Stable resonances form persistent structures,
          transients disturb the field, and recurring motifs reappear as familiar entities —
          a record of the system's history of listening.
        </p>
      </article>
      <article>
        <h2>Narrative</h2>
        <p>
          A language model adds a slower layer, giving language to events the analytical
          system has detected. It does not decide what happened in the sound.
        </p>
      </article>
    </section>
